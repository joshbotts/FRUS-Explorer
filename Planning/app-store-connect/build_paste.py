"""Writes what the owner pastes into App Store Connect, counted, from the listing draft.

Planning/Store-Listing-Draft.md is the copy of record for every text field of the listing. Each
field is the first fenced block under its heading there. This script reads those blocks and writes

    paste/name.txt               Name                         30 characters
    paste/subtitle.txt           Subtitle                     30 characters
    paste/promotional-text.txt   Promotional Text            170 characters
    paste/keywords.txt           Keywords                    100 bytes
    paste/description.txt        Description               4,000 characters
    paste/whats-new.txt          What's New in This Version 4,000 characters (not on a first version)
    paste/review-notes.txt       App Review notes          4,000 bytes
    App-Store-Connect-Entry.md   its field table, between the "generated" markers

The limits and their units are Apple's, read on 2026-11-10 in App Store Connect Help's references
"App information" and "Platform version information": the keywords and the review notes are
limited in bytes, the rest in characters.

Why the files, when the blocks are there to copy:
  - The draft wraps its long blocks at about 100 columns, for reading. App Store Connect keeps a
    pasted line break ("plain text, with line breaks as needed"), so a block pasted as it stands
    would break every paragraph mid-sentence on the product page. A paste file holds one line a
    paragraph, as the TestFlight notes do.
  - Every count in the draft was once written by hand, and three were wrong. The script measures
    the text as it will be pasted and fails when the count the draft prints beside a field is not
    that number, or when a field is over its limit.
  - App Store Connect refused 1.0 (1776)'s Mac TestFlight notes for an invalid character: the
    gear, the multiplication X and the circled i (#1783). A field that holds one of them fails.

Unwrapping, for the fields of more than one line: a blank line ends a paragraph; a line in capitals
after a blank line is a heading and keeps its own line; a line that starts "- " or "1. " at the
margin starts a list item, and an indented line continues the item or paragraph above it; any
other line continues a paragraph, and starts a new one after a heading or a list item.

Stdlib only, macOS's bundled python3 (3.9), no pip. Run from anywhere:
    python3 Planning/app-store-connect/build_paste.py           # count, and rewrite what is out of step
    python3 Planning/app-store-connect/build_paste.py --check   # write nothing; exit 1 if anything is
Run it after any change to a field's block in the draft.
"""

import re
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
DRAFT = REPO / "Planning" / "Store-Listing-Draft.md"
PASTE = HERE / "paste"
SHEET = HERE / "App-Store-Connect-Entry.md"

# (key, the heading its section starts with, the field's name in App Store Connect, limit, unit,
#  paste file, one line only)
FIELDS = [
    ("name", "### App name", "Name", 30, "characters", "name.txt", True),
    ("subtitle", "### Subtitle", "Subtitle", 30, "characters", "subtitle.txt", True),
    ("promo", "### Promotional text", "Promotional Text", 170, "characters", "promotional-text.txt", True),
    ("keywords", "### Keywords", "Keywords", 100, "bytes", "keywords.txt", True),
    ("description", "## 2. Description", "Description", 4000, "characters", "description.txt", False),
    ("whats-new", "## 3. What's New", "What's New in This Version (a first version has no such field)",
     4000, "characters", "whats-new.txt", False),
    ("review-notes", "## 7. App Review notes", "App Review Information: Notes", 4000, "bytes",
     "review-notes.txt", False),
]

# Refused by App Store Connect in 1.0 (1776)'s Mac TestFlight notes (#1783, the plan of record's R2).
REFUSED = {"⚙": "the gear", "✕": "the multiplication X", "ⓘ": "the circled i"}

TABLE_START = "<!-- generated by build_paste.py: the field table. Edit the draft and run the script, never this. -->"
TABLE_END = "<!-- end of the generated field table -->"


def fail(message):
    sys.exit(f"build_paste.py: {message}")


def section_of(lines, heading):
    """The lines of the section that starts with `heading`, up to the next heading of its level or
    above. A field's block has to be inside its own section: without the bound, a deleted block
    would silently hand the field the next field's text."""
    starts = [i for i, line in enumerate(lines) if line.startswith(heading)]
    if len(starts) != 1:
        fail(f"{len(starts)} sections of the draft start with {heading!r}; expected one")
    level = len(heading) - len(heading.lstrip("#"))
    end = len(lines)
    for i in range(starts[0] + 1, len(lines)):
        match = re.match(r"(#+) ", lines[i])
        if match and len(match.group(1)) <= level:
            end = i
            break
    return lines[starts[0]:end]


def block_and_stated_count(section, heading):
    """The first fenced block of a section, and the "N / limit" the draft prints before it."""
    fences = [i for i, line in enumerate(section) if line.strip() == "```"]
    if len(fences) < 2:
        fail(f"no fenced block under {heading!r}")
    block = section[fences[0] + 1:fences[1]]
    stated = re.search(r"(\d[\d,]*) / (\d[\d,]*)", "\n".join(section[:fences[0]]))
    if not stated:
        fail(f"the draft prints no count (N / limit) under {heading!r}, before its block")
    return block, int(stated.group(1).replace(",", "")), int(stated.group(2).replace(",", ""))


def unwrap(block):
    """The block as it is pasted: one line a paragraph, a heading or a list item (the module's
    docstring has the rules)."""
    out = []      # the logical lines; "" is a blank line
    kind = "blank"
    for raw in block:
        text = raw.strip()
        if not text:
            if out and out[-1] != "":
                out.append("")
            kind = "blank"
            continue
        indented = raw[:1] in (" ", "\t")
        is_item = not indented and re.match(r"(- |\d+\. )", text) is not None
        is_heading = (not indented and kind == "blank" and text == text.upper()
                      and any(ch.isalpha() for ch in text))
        if is_heading:
            out.append(text)
            kind = "heading"
        elif is_item:
            out.append(text)
            kind = "item"
        elif (indented and kind in ("item", "paragraph")) or (not indented and kind == "paragraph"):
            out[-1] += " " + text
        else:
            out.append(text)
            kind = "paragraph"
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out)


def measure(text, unit):
    return len(text.encode("utf-8")) if unit == "bytes" else len(text)


def read_fields():
    """Every field as (key, label, text, count, limit, unit, file), failing on anything wrong."""
    lines = DRAFT.read_text(encoding="utf-8").split("\n")
    fields, notes = [], []
    for key, heading, label, limit, unit, file_name, one_line in FIELDS:
        block, stated, stated_limit = block_and_stated_count(section_of(lines, heading), heading)
        if one_line:
            if len(block) != 1:
                fail(f"{label}: its block must be one line, and it has {len(block)}")
            text = block[0].strip()
        else:
            text = unwrap(block)
        count = measure(text, unit)
        if stated_limit != limit:
            fail(f"{label}: the draft says the limit is {stated_limit:,}; Apple's is {limit:,} {unit}")
        if count > limit:
            fail(f"{label}: {count:,} {unit}, over the limit of {limit:,} by {count - limit:,}")
        if stated != count:
            fail(f"{label}: the draft prints {stated:,} / {limit:,} and the text measures {count:,} {unit}. "
                 f"Correct the count under {heading!r}")
        for char, name in REFUSED.items():
            if char in text:
                fail(f"{label}: it holds {name} (U+{ord(char):04X}), which App Store Connect has refused")
        other = sorted({ch for ch in text if ord(ch) > 127})
        if other:
            names = ", ".join(f"{unicodedata.name(ch, 'unnamed').lower()} x{text.count(ch)}" for ch in other)
            notes.append(f"{label}: not ASCII: {names}")
        fields.append((key, label, text, count, limit, unit, file_name))

    by_key = {field[0]: field for field in fields}
    keywords = by_key["keywords"][2].split(",")
    for keyword in keywords:
        if len(keyword.strip()) <= 2:
            fail(f"Keywords: {keyword!r} is not longer than two characters, which Apple requires")
        if keyword != keyword.strip():
            notes.append(f"Keywords: {keyword!r} spends a byte on a space beside its comma")
    name_words = {word.lower() for word in by_key["name"][2].split()}
    for keyword in keywords:
        if keyword.strip().lower() in name_words:
            notes.append(f"Keywords: {keyword.strip()!r} is a word of the app's name, which Apple's reference "
                         "says not to repeat (the draft's §1 offers an alternate)")
    return fields, notes


def field_table(fields):
    rows = [TABLE_START, "", "| Field | Paste the whole of | Now | Apple's limit |", "|---|---|---|---|"]
    for _key, label, _text, count, limit, unit, file_name in fields:
        rows.append(f"| {label} | [paste/{file_name}](paste/{file_name}) | {count:,} | {limit:,} {unit} |")
    rows += ["", TABLE_END]
    return "\n".join(rows)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        fail("the only argument is --check")
    fields, notes = read_fields()

    # A paste file ends where its text ends: no final newline to arrive in a one-line field.
    wanted = {PASTE / file_name: text for _key, _label, text, _count, _limit, _unit, file_name in fields}
    sheet = SHEET.read_text(encoding="utf-8") if SHEET.exists() else None
    if sheet is None or sheet.count(TABLE_START) != 1 or sheet.count(TABLE_END) != 1:
        fail(f"{SHEET.name} must hold the field table's two markers, once each")
    before, rest = sheet.split(TABLE_START)
    _old, after = rest.split(TABLE_END)
    wanted[SHEET] = before + field_table(fields) + after

    stale = [path for path, text in wanted.items()
             if not path.exists() or path.read_text(encoding="utf-8") != text]
    extra = sorted(set(PASTE.glob("*.txt")) - set(wanted)) if PASTE.exists() else []

    for _key, label, _text, count, limit, unit, _file_name in fields:
        print(f"{label:62} {count:>5,} / {limit:,} {unit}")
    for note in notes:
        print(f"note: {note}")

    if check:
        for path in stale:
            print(f"out of step: {path.relative_to(REPO)}")
        for path in extra:
            print(f"not a field's file: {path.relative_to(REPO)}")
        if stale or extra:
            sys.exit(1)
        print("in step with the draft")
        return
    PASTE.mkdir(exist_ok=True)
    for path in stale:
        path.write_text(wanted[path], encoding="utf-8")
        print(f"wrote {path.relative_to(REPO)}")
    for path in extra:
        print(f"not a field's file, left alone: {path.relative_to(REPO)}")
    if not stale:
        print("nothing to write: in step with the draft")


if __name__ == "__main__":
    main()
